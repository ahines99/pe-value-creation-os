async def planning(s: Session) -> str:
    cid = "beacon-pricing"
    run = (await s.tool("start_diagnostic_run", company_id=cid, mode="interactive"))["run_id"]
    pw = await s.tool("price_waterfall", company_id=cid)
    o = await s.tool(
        "propose_opportunity",
        run_id=run,
        lever="pricing",
        baseline_metric="legacy_price_book_arr",
        title="Migrate legacy price-book customers",
        low=scen("0.1", "0.4"),
        base=scen("0.2", "0.55"),
        high=scen("0.25", "0.7"),
        confidence="medium",
        rationale="Legacy share above policy",
        evidence_ids=pw["evidence_ids"],
        one_time_cost="75000",
    )
    await s.tool("size_value_case", company_id=cid, opportunity_id=o["opportunity_id"])
    await s.tool("prioritize_opportunities", run_id=run)
    plan = await s.tool("draft_100_day_plan", run_id=run)
    out = [
        "# Worked example: 100-day plan (Beacon, fictional)\n\n",
        HEADER,
        f"## Plan summary\n\nTotal base-case run-rate EBITDA {money(plan['total_run_rate_ebitda_base'])}; in-year "
        f"{money(plan['total_in_year_ebitda_base'])}.\n\n## Workstreams\n\n",
    ]
    for ws in plan["workstreams"]:
        out.append(f"### {ws['name']} (owner: {ws['owner_role']})\n\n")
        out += [
            f"- {i['title']} [{i['classification']}]: run-rate {money(i['run_rate_ebitda_base'])}, in-year "
            f"{money(i['in_year_ebitda_base'])}\n"
            for i in ws["initiatives"]
        ]
        for k, v in ws["milestones"].items():
            out.append(f"- **{k}**: " + "; ".join(v) + "\n")
        out.append("\n| KPI | Baseline | Day-100 target | Run-rate target | Monitorable |\n|---|---|---|---|---|\n")
        out += [
            f"| {k['description']} | {k['baseline']} | {k['day_100_target']} | {k['run_rate_target']} | "
            f"{'yes' if k['monitorable'] else 'no'} |\n"
            for k in ws["kpis"]
        ]
        out.append("\n" + "".join(f"- Dependency: {d}\n" for d in ws["dependencies"]))
        out.append("".join(f"- Risk: {r}\n" for r in ws["risks"]) + "\n")
    out.append(
        "## Decisions requiring approval\n\n" + "".join(f"- {d}\n" for d in plan["decisions_requiring_approval"])
    )
    out.append("\n")
    return "".join(out) + s.transcript()


async def main() -> None:
    configure_logging(stream=io.StringIO())
    tmp = Path(tempfile.mkdtemp())
    ctx = RunContext(
        repo=InMemoryRepository(FileSystemEvidenceStore(tmp / "ev")),
        adapter=FixtureAdapter(),
        policy=get_policy(),
        actor="mcp",
    )
    _runtime.set_ctx(ctx)
    jobs = {
        "pe-value-creation-diagnostic": diagnostic,
        "pricing-value-creation": pricing,
        "saas-unit-economics": unit_economics,
        "customer-retention": retention,
        "ai-opportunity-assessment": ai,
        "100-day-planning": planning,
    }
    with security.principal_scope(
        security.Principal(
            subject="model:example", companies=frozenset({"beacon-pricing", "cedar-churn"}), principal_type="model"
        )
    ):
        async with Client(build_server()) as c:
            for skill, fn in jobs.items():
                text = await fn(Session(c))
                path = ROOT / "skills" / skill / "references" / "worked-example.md"
                path.parent.mkdir(exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
                print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    anyio.run(main)
